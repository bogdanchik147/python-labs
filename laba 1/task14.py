a = set(map(int, input("Введите числа первого набора: ").split()))
b = set(map(int, input("Введите числа второго набора: ").split()))

print("Общие числа:", a & b)
print("Все числа без повторений:", a ^ b)
print("Есть в первом, но нет во втором:", a - b)
print("Есть во втором, но нет в первом:", b - a)